/**
 * Generates sql/seed-memorials.sql from data/memorials.json.
 *
 *   node scripts/build-memorial-seed.mjs
 *
 * The seed upserts by lower(full_name) (needs migration 009), never touches
 * photo_url / photo_key, and never deletes rows, so it is safe to re-run.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rows = JSON.parse(readFileSync(join(root, 'data', 'memorials.json'), 'utf8'));

const lit = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const values = rows.map(r =>
  `  (${[r.full_name, r.batch, r.specialty, r.birth_year, r.death_year, r.sort_order].map(lit).join(', ')})`
).join(',\n');

const sql = `-- GENERATED by scripts/build-memorial-seed.mjs from data/memorials.json. Do not edit by hand.
-- Requires migrations 006-009. Safe to re-run: upserts by name, keeps photos.
-- sort_order 0 = most recently deceased (shown first).

INSERT INTO memorials (full_name, batch, specialty, birth_year, death_year, sort_order)
VALUES
${values}
ON CONFLICT (lower(full_name)) WHERE deleted_at IS NULL DO UPDATE SET
  batch = EXCLUDED.batch,
  specialty = EXCLUDED.specialty,
  birth_year = EXCLUDED.birth_year,
  death_year = EXCLUDED.death_year,
  sort_order = EXCLUDED.sort_order;
`;

writeFileSync(join(root, 'sql', 'seed-memorials.sql'), sql);
console.log(`Wrote sql/seed-memorials.sql (${rows.length} memorials)`);
